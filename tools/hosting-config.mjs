#!/usr/bin/env node
/**
 * AETHER GT — hosting configuration generator (Phase 8B). Node 18+, no dependencies.
 *
 *   node tools/hosting-config.mjs            write the five files below
 *   node tools/hosting-config.mjs --check    exit 1 if a committed file differs from what would be generated
 *
 * Generates, from ONE source of truth (tools/url-map.mjs + the cache table below):
 *   _headers          Cloudflare Pages (and Netlify-format hosts)
 *   _redirects        Cloudflare Pages (and Netlify-format hosts)
 *   vercel.json       Vercel
 *   .htaccess         Apache (mod_rewrite, mod_headers, mod_mime)
 *   deploy/nginx.conf nginx (a complete server block; not part of the site root)
 *
 * Scope of Phase 8B: clean-URL serving, the 20 redirects (query string kept, no loops), cache lifetimes, MIME types.
 * Security headers, CSP and SEO are later phases and are deliberately absent.
 *
 * Do not edit the generated files by hand: edit tools/url-map.mjs or this file and run the generator again.
 * tests/hosting-config.test.mjs fails if a generated file is stale.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CARS, REDIRECTS } from './url-map.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Cache policy, shared by every host. Files are not fingerprinted, so CSS/JS/HTML must revalidate;
 * binary assets (images, fonts, GLB models, icons) may be cached for a week. Rename a file when replacing it.
 * `paths` are the URL patterns (Cloudflare/Vercel/nginx); `exts` are the same files by extension (Apache,
 * whose .htaccess cannot match URL prefixes). tests/hosting-config.test.mjs proves both describe the same files.
 */
export const CACHE = {
  revalidate: {
    value: 'public, max-age=0, must-revalidate',
    paths: ['/', '/collection.html', '/404.html', '/cars/*', '/css/*', '/js/*'],
    exts: ['html', 'css', 'js'],
  },
  binary: {
    value: 'public, max-age=604800',
    paths: ['/assets/*', '/favicon.ico'],
    exts: ['jpg', 'jpeg', 'png', 'webp', 'svg', 'ico', 'woff', 'woff2', 'glb'],
  },
};

/** MIME types the site needs. Used by Apache (AddType) and nginx (types{}); Cloudflare and Vercel set their own. */
export const MIME = {
  html: 'text/html', css: 'text/css', js: 'text/javascript', json: 'application/json',
  webmanifest: 'application/manifest+json', xml: 'application/xml', txt: 'text/plain',
  svg: 'image/svg+xml', png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', webp: 'image/webp',
  ico: 'image/x-icon', woff: 'font/woff', woff2: 'font/woff2', glb: 'model/gltf-binary',
};

const BANNER = 'GENERATED by tools/hosting-config.mjs from tools/url-map.mjs. Do not edit by hand; run: node tools/hosting-config.mjs';
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); // regex-escape for Apache patterns
const stripSlash = (p) => p.replace(/^\//, '');

/**
 * Loop safety is a property of the data, so it is enforced here, before any host file is written:
 * a redirect never points at itself, never points at another redirect source, and always points at a clean car URL.
 */
export function assertNoLoops(redirects = REDIRECTS, cars = CARS) {
  const from = new Set();
  const clean = new Set(cars.map((c) => c.url));
  for (const r of redirects) {
    if (from.has(r.from)) throw new Error(`duplicate redirect source ${r.from}`);
    from.add(r.from);
  }
  for (const r of redirects) {
    if (r.from === r.to) throw new Error(`redirect loop: ${r.from} -> itself`);
    if (from.has(r.to)) throw new Error(`redirect chain: ${r.from} -> ${r.to} -> ...`);
    if (!clean.has(r.to)) throw new Error(`redirect target ${r.to} is not a clean car URL`);
    if (r.to.includes('?') || r.to.includes('#')) throw new Error(`redirect target ${r.to} must be a bare path (the query string is carried over by the host)`);
  }
}

/** Cloudflare Pages / Netlify-format `_redirects`: one static rule per line, explicit 301. */
export function renderRedirectsFile(redirects = REDIRECTS) {
  const w = Math.max(...redirects.map((r) => r.from.length));
  return [
    `# ${BANNER}`,
    '# Static 301 redirects. First match wins and the target never matches another rule, so there is no chain and no loop.',
    '# Cloudflare Pages: max 2,000 static rules per file, 1,000 characters per line.',
    ...redirects.map((r) => `${r.from.padEnd(w)}  ${r.to}  301`),
    '',
  ].join('\n');
}

/** Cloudflare Pages / Netlify-format `_headers`: cache lifetimes only. Rule sets are disjoint, so no header is merged twice. */
export function renderHeadersFile() {
  const lines = [`# ${BANNER}`, '# Cache lifetimes only (Phase 8B). Security headers and CSP are a later phase.', '# Cloudflare Pages: max 100 rules, 2,000 characters per header line.', ''];
  for (const group of Object.values(CACHE)) {
    for (const p of group.paths) lines.push(p, `  Cache-Control: ${group.value}`, '');
  }
  return lines.join('\n');
}

/** vercel.json: explicit 301s, rewrites for the clean URLs, cache headers. No cleanUrls (it would also move /collection.html). */
export function renderVercelJson(redirects = REDIRECTS, cars = CARS) {
  // Vercel's `trailingSlash: false` redirects /cars/<slug>/ itself. An explicit `/cars/<slug>/` rule is not emitted
  // because Vercel's path matching may ignore a trailing slash, and such a rule could then match its own target (a loop).
  const explicit = redirects.filter((r) => !r.from.endsWith('/'));
  const conf = {
    trailingSlash: false,
    redirects: explicit.map((r) => ({ source: r.from, destination: r.to, statusCode: 301 })),
    rewrites: cars.map((c) => ({ source: c.url, destination: `/${c.file}` })),
    headers: Object.values(CACHE).flatMap((g) => g.paths.map((p) => ({
      source: p.endsWith('/*') ? `${p.slice(0, -2)}/(.*)` : p,
      headers: [{ key: 'Cache-Control', value: g.value }],
    }))),
  };
  return JSON.stringify(conf, null, 2) + '\n';
}

/**
 * Apache .htaccess. Redirects test THE_REQUEST (the original request line), which an internal rewrite never changes.
 * Without that, the internal rewrite /cars/x -> cars/x.html would be matched again by the `cars/x.html` redirect: a loop.
 * mod_rewrite keeps the original query string when the substitution has none.
 */
export function renderHtaccess(redirects = REDIRECTS, cars = CARS) {
  const out = [
    `# ${BANNER}`,
    '# Needs mod_rewrite, mod_mime and mod_headers, and AllowOverride FileInfo (ErrorDocument, AddType, RewriteRule and Header all need it).',
    '# The site must be served from the root of the domain.',
    '',
    'ErrorDocument 404 /404.html',
    '',
    '<IfModule mod_mime.c>',
    ...Object.entries(MIME).filter(([ext]) => ['webmanifest', 'glb', 'woff', 'woff2', 'webp', 'js', 'svg'].includes(ext)).map(([ext, type]) => `  AddType ${type} .${ext}`),
    '  AddDefaultCharset UTF-8',
    '</IfModule>',
    '',
    '<IfModule mod_rewrite.c>',
    '  RewriteEngine On',
    '',
    '  # 301 redirects (old and variant URLs -> clean URL)',
  ];
  for (const r of redirects) {
    out.push(
      `  RewriteCond %{THE_REQUEST} ^[A-Z]+\\ ${esc(r.from)}[?\\ ]`,
      `  RewriteRule ^${esc(stripSlash(r.from))}$ ${r.to} [R=301,L]`,
    );
  }
  out.push('', '  # Clean URLs: serve the file without redirecting');
  for (const c of cars) out.push(`  RewriteRule ^${esc(stripSlash(c.url))}$ ${c.file} [L]`);
  out.push('</IfModule>', '', '<IfModule mod_headers.c>');
  for (const g of Object.values(CACHE)) {
    out.push(`  <FilesMatch "\\.(${g.exts.join('|')})$">`, `    Header set Cache-Control "${g.value}"`, '  </FilesMatch>');
  }
  out.push('</IfModule>', '');
  return out.join('\n');
}

/**
 * nginx: a complete server block (include it from http { }). Exact-match locations keep every rule independent:
 * try_files with a file as its first argument serves in place and does not trigger a second location lookup, so the
 * clean URL never meets its own `.html` redirect. `absolute_redirect off` avoids a wrong scheme or port behind a proxy.
 */
export function renderNginx(redirects = REDIRECTS, cars = CARS) {
  const cache = (v) => `add_header Cache-Control "${v}";`;
  const out = [
    `# ${BANNER}`,
    '# Include inside http { } (for example /etc/nginx/conf.d/aether-gt.conf). Set server_name, root and TLS yourself.',
    'server {',
    '  listen 80;',
    '  server_name _;',
    '  root /var/www/aether-gt;   # the folder made by: node tools/prepare-launch.mjs https://your-domain --dist <folder>',
    '  index index.html;',
    '  charset utf-8;',
    '  absolute_redirect off;',
    '  error_page 404 /404.html;',
    '',
    '  types {',
    ...Object.entries(MIME).map(([ext, type]) => `    ${type.padEnd(28)} ${ext};`),
    '  }',
    '',
    '  # 301 redirects (old and variant URLs -> clean URL); $is_args$args keeps the query string',
    ...redirects.map((r) => `  location = ${r.from} { return 301 ${r.to}$is_args$args; }`),
    '',
    '  # Clean URLs: serve the file without redirecting',
    ...cars.map((c) => `  location = ${c.url} { ${cache(CACHE.revalidate.value)} try_files /${c.file} =404; }`),
    '',
    '  # Any other path that ends in a slash (/cars/, /assets/ ...) is not a page',
    '  location ~ ^/.+/$ { return 404; }',
    '',
    '  # Pages and static files',
    `  location = / { ${cache(CACHE.revalidate.value)} try_files /index.html =404; }`,
    `  location = /collection.html { ${cache(CACHE.revalidate.value)} try_files $uri =404; }`,
    `  location = /404.html { ${cache(CACHE.revalidate.value)} try_files $uri =404; }`,
    `  location = /favicon.ico { ${cache(CACHE.binary.value)} try_files $uri =404; }`,
    `  location /css/ { ${cache(CACHE.revalidate.value)} try_files $uri =404; }`,
    `  location /js/ { ${cache(CACHE.revalidate.value)} try_files $uri =404; }`,
    `  location /assets/ { ${cache(CACHE.binary.value)} try_files $uri =404; }`,
    '  location / { try_files $uri =404; }',
    '}',
    '',
  ];
  return out.join('\n');
}

/** Every generated file: path (relative to the project root) -> content. */
export function generateAll() {
  assertNoLoops();
  return {
    '_headers': renderHeadersFile(),
    '_redirects': renderRedirectsFile(),
    'vercel.json': renderVercelJson(),
    '.htaccess': renderHtaccess(),
    'deploy/nginx.conf': renderNginx(),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = generateAll();
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files).filter(([f, s]) => !existsSync(join(ROOT, f)) || readFileSync(join(ROOT, f), 'utf8') !== s).map(([f]) => f);
    console.log(stale.length ? `Stale or missing: ${stale.join(', ')}\nRun: node tools/hosting-config.mjs` : `Hosting config is up to date (${Object.keys(files).length} files).`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [f, s] of Object.entries(files)) {
    mkdirSync(dirname(join(ROOT, f)), { recursive: true });
    writeFileSync(join(ROOT, f), s);
    console.log(`wrote ${f}`);
  }
}
